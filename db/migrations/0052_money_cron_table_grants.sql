-- money_cron has BYPASSRLS but previously had no table privileges.
-- SET LOCAL ROLE money_cron therefore failed with 42501 on DELETE/SELECT.
GRANT USAGE ON SCHEMA public TO money_cron;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO money_cron;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO money_cron;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA public TO money_cron;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO money_cron;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO money_cron;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT EXECUTE ON FUNCTIONS TO money_cron;
